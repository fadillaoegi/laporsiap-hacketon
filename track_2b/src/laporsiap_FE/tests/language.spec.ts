import { test, expect } from '@playwright/test'
import { readFile } from 'node:fs/promises'

test('English is the default and language changes preserve input and persist on reload', async ({ page }) => {
  await page.goto('/')
  await page.screenshot({ path: '../../docs/screenshots/06-input-desktop-english.png' })
  const language = page.getByRole('combobox', { name: 'Language / Bahasa' })
  await expect(language).toHaveValue('en')
  await expect(page.locator('html')).toHaveAttribute('lang', 'en')
  await expect(page).toHaveTitle('LaporSiap — Prepare report materials')
  await page.getByRole('button', { name: 'Save & continue' }).click()
  await expect(page.getByRole('alert')).toContainText('Enter a title and conversation.')
  await page.getByRole('textbox', { name: 'Case title', exact: true }).fill('Belum diketahui')
  await language.selectOption('id')
  await expect(page.locator('html')).toHaveAttribute('lang', 'id')
  await expect(page.getByRole('alert')).toContainText('Judul dan percakapan wajib diisi.')
  await expect(page.getByRole('textbox', { name: 'Judul kasus', exact: true })).toHaveValue('Belum diketahui')
  // A fresh form is intentionally not saved as a case by changing languages.
  await page.getByRole('textbox', { name: 'Judul kasus', exact: true }).fill('')
  await page.reload()
  await expect(language).toHaveValue('id')
  await expect(page).toHaveTitle('LaporSiap — Siapkan bahan laporan')
  await language.selectOption('en')
  await page.reload()
  await expect(language).toHaveValue('en')
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(language).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
})

test('English review and bilingual exports retain original evidence and review confirmation', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Try an example', exact: true }).click()
  await page.getByRole('button', { name: 'Save & continue' }).click()
  await expect(page.getByRole('button', { name: 'Create draft with Apertus', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: 'Use a manual draft' }).click()
  await expect(page.getByText('MANUAL DRAFT', { exact: true })).toBeVisible()
  await expect(page.getByText('Transfer 1: missing transfer date.', { exact: true })).toBeVisible()
  const chronology = page.getByRole('textbox', { name: 'Chronology M1', exact: true })
  const description = 'Pengirim menawarkan tugas memberi like dengan janji komisi Rp50.000 per hari.'
  await chronology.fill(description)
  await page.getByRole('combobox', { name: 'Language / Bahasa' }).selectOption('id')
  await expect(page.getByRole('textbox', { name: 'Kronologi M1', exact: true })).toHaveValue(description)
  await expect(page.getByRole('button', { name: 'Konfirmasi & lanjut' })).toBeDisabled()
  await page.getByRole('combobox', { name: 'Language / Bahasa' }).selectOption('en')
  await page.getByRole('button', { name: 'Save edits' }).click()
  await page.screenshot({ path: '../../docs/screenshots/07-review-desktop-english.png' })
  for (const checkbox of await page.getByRole('checkbox', { name: 'I have compared this entry with its source' }).all()) await checkbox.check()
  await page.getByRole('checkbox', { name: 'I have checked the accounts, amounts, dates, and transfer status.' }).check()
  await page.getByRole('checkbox', { name: /I have checked the review flags/ }).check()
  await page.getByRole('button', { name: 'Confirm & continue' }).click()
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Download chronology TXT' }).click()
  const englishFile = await download
  const english = await readFile(await englishFile.path() as string, 'utf8')
  expect(english).toContain('LAPORSIAP — SUPPORTING REPORT MATERIALS')
  expect(english).toContain('Successful transfer amount reported by the user (known amounts): 180000 rupiah')
  expect(english).toContain('Transfer 1: missing transfer date.')
  expect(english).toContain(description)
  expect(english).toContain('I have just sent IDR 180,000. I have not recorded the transfer time.')
  await page.getByRole('combobox', { name: 'Language / Bahasa' }).selectOption('id')
  await expect(page.getByRole('button', { name: 'Unduh paket ZIP' })).toBeEnabled()
  const idDownload = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Unduh kronologi TXT' }).click()
  const file = await idDownload
  const indonesian = await readFile(await file.path() as string, 'utf8')
  expect(indonesian).toContain('LAPORSIAP — BAHAN BANTU LAPORAN')
  expect(indonesian).toContain(description)
  await page.getByRole('combobox', { name: 'Language / Bahasa' }).selectOption('en')
  await page.getByRole('button', { name: /Review & edit/ }).click()
  for (const width of [320, 390, 768, 1440]) {
    await page.setViewportSize({ width, height: 844 })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), `Horizontal overflow at ${width}px`).toBe(true)
  }
  await page.setViewportSize({ width: 390, height: 844 })
  await page.screenshot({ path: '../../docs/screenshots/05-review-mobile-english.png', fullPage: true })
  await page.screenshot({ path: '../../docs/screenshots/08-review-mobile-english-viewport.png' })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
})

test('backend validation appears in the selected language', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('textbox', { name: 'Case title', exact: true }).fill('Synthetic invalid date')
  await page.getByLabel('Conversation format').selectOption('whatsapp_bracket_dmy')
  await page.getByRole('textbox', { name: 'Conversation', exact: true }).fill('[31/02/2026, 09:00] Raka: Tanggal tidak valid.')
  await page.getByRole('button', { name: 'Save & continue' }).click()
  await expect(page.getByRole('alert')).toContainText('The TXT header date/time is invalid.')
  await page.getByRole('combobox', { name: 'Language / Bahasa' }).selectOption('id')
  await expect(page.getByRole('alert')).toContainText('Tanggal/jam header TXT tidak valid.')
})
