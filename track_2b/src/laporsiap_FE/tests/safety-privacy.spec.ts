import { test, expect } from '@playwright/test'
import type { Response } from '../src/domain/models'

test('default redaction, exact preview consent and original sources stay distinct', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('textbox', { name: 'Case title', exact: true }).fill('Fictional privacy regression')
  const original = '[10/10/2026, 10:00] Nadia: My email is nadia@example.test. My phone is +6281234567890. Account 1234567890. I sent IDR 180,000. Address Jalan Mawar 7.'
  await page.getByLabel('Conversation format').selectOption('whatsapp_bracket_dmy')
  await page.getByRole('textbox', { name: 'Conversation', exact: true }).fill(original)
  await page.getByRole('checkbox', { name: 'This is simulated data', exact: true }).check()
  const pending = page.waitForResponse(r => r.request().method() === 'POST' && r.url().endsWith('/api/cases'))
  await page.getByRole('button', { name: 'Save & continue' }).click()
  const data: Response = await (await pending).json()
  await expect(page.getByRole('checkbox', { name: 'Mask personal information before sending to AI' })).toBeChecked()
  await page.getByText('View all messages to be sent', { exact: true }).click()
  const preview = page.locator('.preview-messages')
  await expect(preview).toContainText('IDR 180,000')
  await expect(preview).not.toContainText('nadia@example.test')
  await expect(preview).not.toContainText('+6281234567890')
  await expect(preview).not.toContainText('1234567890')
  await expect(preview).toContainText('Jalan Mawar 7')
  const consent = page.getByRole('checkbox', { name: /I consent to sending/ })
  await consent.check()
  await page.getByRole('textbox', { name: 'Additional terms to mask' }).fill('Jalan Mawar 7')
  await expect(consent).not.toBeChecked()
  await expect(preview).not.toContainText('Jalan Mawar 7')
  // UI-only provider stub; the real provider boundary is checked in Go.
  await page.route('**/api/cases/*/draft', async route => {
    const req = route.request().postDataJSON()
    expect(req.privacy).toEqual({ mode: 'redacted', terms: ['Jalan Mawar 7'] })
    expect(req.preview_hash).toMatch(/^[0-9a-f]{64}$/)
    expect(req.external_consent).toBe(true)
    await route.fulfill({ json: { ...data, case: { ...data.case, draft: { origin: 'apertus', model: 'swiss-ai/apertus-v1.5-70b', language: 'en', privacy_mode: 'redacted', checks: [], events: data.case.messages.map(m => ({ source_id: m.id, evidence: m.text, description: 'The sender states they sent IDR 180,000.' })) } } } })
  })
  await consent.check()
  await page.getByRole('button', { name: 'Create draft with Apertus', exact: true }).click()
  await expect(page.getByText('APERTUS DRAFT', { exact: true })).toBeVisible()
  await expect(page.locator('.event-source blockquote')).toContainText('nadia@example.test')
  const saved = await page.request.get(`/api/cases/${data.case.id}`, { headers: { Authorization: `Bearer ${data.token}` } })
  expect((await saved.json()).case.raw_chat).toBe(original)
  await page.getByRole('button', { name: '+ Create a new case', exact: true }).click()
  await page.getByRole('button', { name: 'Try an example', exact: true }).click()
  await page.getByRole('button', { name: 'Save & continue', exact: true }).click()
  await expect(page.getByRole('checkbox', { name: 'Mask personal information before sending to AI' })).toBeChecked()
  await expect(page.getByRole('textbox', { name: 'Additional terms to mask' })).toHaveValue('')
})

for (const language of ['en', 'id'] as const) {
  test(`renew access and permanent deletion work in ${language}`, async ({ page }) => {
    await page.goto('/')
    await page.getByRole('combobox', { name: 'Language / Bahasa' }).selectOption(language)
    await page.getByRole('button', { name: language === 'en' ? 'Try an example' : 'Coba contoh', exact: true }).click()
    const pending = page.waitForResponse(r => r.request().method() === 'POST' && r.url().endsWith('/api/cases'))
    await page.getByRole('button', { name: language === 'en' ? 'Save & continue' : 'Simpan & lanjut' }).click()
    const data: Response = await (await pending).json()
    await page.getByText(language === 'en' ? 'Your data and access' : 'Data dan akses Anda', { exact: true }).click()
    const rotate = page.waitForResponse(r => r.url().endsWith('/access/rotate'))
    await page.getByRole('button', { name: language === 'en' ? 'Renew session access' : 'Perbarui akses sesi', exact: true }).click()
    const renewed: Response = await (await rotate).json()
    expect(renewed.token).not.toBe(data.token)
    const old = await page.request.get(`/api/cases/${data.case.id}`, { headers: { Authorization: `Bearer ${data.token}` } })
    expect(old.status()).toBe(404)
    await page.reload()
    await expect(page.getByRole('textbox', { name: language === 'en' ? 'Case title' : 'Judul kasus', exact: true })).toHaveValue(data.case.title)
    await page.getByText(language === 'en' ? 'Your data and access' : 'Data dan akses Anda', { exact: true }).click()
    const remove = page.getByRole('button', { name: language === 'en' ? 'Permanently delete case' : 'Hapus kasus secara permanen', exact: true })
    await expect(remove).toBeDisabled()
    await page.getByRole('textbox', { name: language === 'en' ? 'Type DELETE to delete' : 'Ketik DELETE untuk menghapus' }).fill('DELETE')
    await remove.click()
    await expect(page.getByRole('status')).toContainText(language === 'en' ? 'deleted from the database' : 'dihapus dari database')
    expect((await page.request.get(`/api/cases/${data.case.id}`, { headers: { Authorization: `Bearer ${renewed.token}` } })).status()).toBe(404)
    expect(await page.evaluate(() => JSON.parse(sessionStorage.getItem('laporsiap-access') || '[]'))).toEqual([])
    await expect(page.getByRole('textbox', { name: language === 'en' ? 'Case title' : 'Judul kasus', exact: true })).toHaveValue('')
  })
}
