import { test, expect } from '@playwright/test'
import path from 'node:path'
import { readFile } from 'node:fs/promises'

test.beforeEach(async ({ page }) => {
  await page.addInitScript(() => localStorage.setItem('laporsiap-language', 'id'))
})

test('synthetic case: manual review, attachment, export, and invalidation after input edit', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', e => errors.push(e.message))
  await page.goto('/')
  const officialChannel = page.getByRole('link', { name: 'Buka IASC', exact: true })
  await expect(officialChannel).toBeVisible()
  await expect(officialChannel).toHaveAttribute('href', 'https://iasc.ojk.go.id/')
  await page.screenshot({ path: path.resolve('../../docs/screenshots/01-input-desktop.png'), fullPage: true })
  await page.getByRole('button', { name: 'Coba contoh', exact: true }).click()
  await page.getByRole('button', { name: 'Simpan & lanjut' }).click()
  const ai = page.getByRole('button', { name: 'Susun draft dengan Apertus', exact: true })
  await expect(ai).toBeDisabled()
  await page.getByRole('checkbox', { name: /Saya setuju mengirim/ }).check()
  await expect(ai).toBeEnabled()
  // UI path remains usable without making a live provider request.
  await page.getByRole('button', { name: 'Gunakan draft manual' }).click()
  await expect(page.getByText('DRAFT MANUAL', { exact: true })).toBeVisible()
  await expect(page.getByText('Rp 180.000', { exact: true }).first()).toBeVisible()
  const first = page.getByRole('textbox', { name: 'Kronologi M1', exact: true })
  await first.fill('Pengirim menawarkan tugas memberi like dengan janji komisi Rp50.000 per hari.')
  await expect(page.getByRole('checkbox', { name: 'Saya telah mencocokkan entri ini dengan sumber' }).first()).toBeDisabled()
  await page.getByRole('button', { name: 'Simpan koreksi' }).click()
  await expect(page.getByText('Koreksi tersimpan.', { exact: false })).toBeVisible()
  await page.getByRole('button', { name: /Bahan kasus/ }).click()
  const reference = await readFile(path.resolve('tests/fixtures/valid-reference.pdf'))
  await page.locator('input[type=file][accept="image/png,image/jpeg,application/pdf"]').setInputFiles({ name: 'bukti-referensi.pdf', mimeType: 'application/pdf', buffer: reference })
  await expect(page.getByText('bukti-referensi.pdf', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: /Periksa & koreksi/ }).click()
  const checks = page.getByRole('checkbox', { name: 'Saya telah mencocokkan entri ini dengan sumber' })
  await expect(checks).toHaveCount(5)
  for (const checkbox of await checks.all()) await checkbox.check()
  await page.getByRole('checkbox', { name: /Saya telah memeriksa rekening/ }).check()
  await page.getByRole('checkbox', { name: /Saya telah memeriksa tanda review/ }).check()
  await page.screenshot({ path: path.resolve('../../docs/screenshots/02-review-desktop.png'), fullPage: true })
  await page.getByRole('button', { name: 'Konfirmasi & lanjut' }).click()
  await expect(page.getByRole('button', { name: 'Unduh paket ZIP' })).toBeEnabled()
  await page.screenshot({ path: path.resolve('../../docs/screenshots/03-export-desktop.png'), fullPage: true })
  const event = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Unduh paket ZIP' }).click()
  const file = await event
  expect(file.suggestedFilename()).toMatch(/laporsiap-revisi-\d+\.zip/)
  await file.saveAs(path.resolve('../../tmp/browser-demo.zip'))
  await page.reload()
  await expect(page.getByRole('button', { name: 'Unduh paket ZIP' })).toBeEnabled()
  await page.getByRole('button', { name: /Bahan kasus/ }).click()
  await page.getByRole('textbox', { name: 'Judul kasus', exact: true }).fill('Simulasi setelah koreksi')
  await page.getByRole('button', { name: /Ekspor bahan/ }).click()
  await expect(page.getByRole('button', { name: 'Unduh paket ZIP' })).toBeDisabled()
  await page.getByRole('button', { name: /Bahan kasus/ }).click()
  await page.getByRole('button', { name: 'Simpan & lanjut' }).click()
  await page.getByRole('button', { name: /Ekspor bahan/ }).click()
  await expect(page.getByRole('button', { name: 'Unduh paket ZIP' })).toBeDisabled()
  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByRole('button', { name: /Periksa & koreksi/ }).click()
  await page.screenshot({ path: path.resolve('../../docs/screenshots/04-review-mobile.png'), fullPage: true })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  expect(errors).toEqual([])
})
