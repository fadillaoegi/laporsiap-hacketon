import { test, expect } from '@playwright/test'
import { mkdir, readFile } from 'node:fs/promises'
import path from 'node:path'
import type { Response } from '../src/domain/models'

test('AI preview keeps exact sources and language changes require fresh consent', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Try an example', exact: true }).click()
  const conversation = await page.getByRole('textbox', { name: 'Conversation', exact: true }).inputValue()
  expect(conversation).toContain('I have just sent IDR 180,000.')
  expect(conversation).toContain('Nadia: Hi Raka,')
  expect(conversation).toContain('****4821')
  await expect(page.getByRole('checkbox', { name: 'This is simulated data', exact: true })).toBeChecked()
  await expect(page.locator('.simulation-banner')).toContainText('SIMULATED DATA')
  await expect(page.locator('body')).not.toContainText(/\bdemo\b/i)
  const created = page.waitForResponse(res => res.url().endsWith('/api/cases') && res.request().method() === 'POST')
  await page.getByRole('button', { name: 'Save & continue' }).click()
  const data: Response = await (await created).json()
  expect(data.case.synthetic).toBe(true)
  // Explicit original mode remains available after checking the disclosure.
  await page.getByRole('checkbox', { name: 'Mask personal information before sending to AI', exact: true }).uncheck()
  await page.getByText('View all messages to be sent', { exact: true }).click()
  const preview = page.locator('.preview-messages')
  await expect(preview.locator('blockquote')).toHaveCount(data.case.messages.length)
  for (let i = 0; i < data.case.messages.length; i++) await expect(preview.locator('blockquote').nth(i)).toHaveText(data.case.messages[i].text)
  await expect(preview).not.toContainText('****7392')
  const picker = page.getByRole('combobox', { name: 'Language / Bahasa' })
  await page.getByRole('checkbox', { name: /I consent to sending/ }).check()
  await picker.selectOption('id')
  await expect(page.locator('.simulation-banner')).toContainText('DATA SIMULASI')
  await expect(page.locator('body')).not.toContainText(/\bdemo\b/i)
  await expect(page.getByRole('checkbox', { name: /Saya setuju mengirim/ })).not.toBeChecked()
  await expect(page.getByRole('button', { name: 'Susun draft dengan Apertus', exact: true })).toBeDisabled()
  await picker.selectOption('en')
  await expect(preview.locator('blockquote').nth(0)).toHaveText(data.case.messages[0].text)
  await page.route('**/api/cases/*/draft', async route => {
    expect(route.request().headers()['accept-language']).toBe('en')
    expect(route.request().postDataJSON().external_consent).toBe(true)
    await route.fulfill({ json: { ...data, case: { ...data.case, draft: {
      origin: 'apertus', model: 'swiss-ai/apertus-v1.5-70b', language: 'en',
      checks: [{ event_index: 4, source_id: 'M5', flags: ['transfer_status_requires_review', 'relative_time_requires_review'] }],
      events: data.case.messages.map(m => ({ source_id: m.id, evidence: m.text, description: 'Synthetic response used only for browser regression.' })),
    } } } })
  })
  await page.getByRole('checkbox', { name: /I consent to sending/ }).check()
  await page.getByRole('button', { name: 'Create draft with Apertus', exact: true }).click()
  await expect(page.getByText('APERTUS DRAFT', { exact: true })).toBeVisible()
  await expect(page.getByText('The source describes an incomplete or failed transfer.', { exact: false })).toBeVisible()
  await expect(page.getByText('Check the timing in the message:', { exact: false })).toBeVisible()
  await expect(page.locator('.review-toolbar .draft-language')).toContainText('English')
  await picker.selectOption('id')
  await expect(page.locator('.review-toolbar .draft-language')).toContainText('English')
  await expect(page.getByText('Sumber menyebut status belum selesai atau gagal.', { exact: false })).toBeVisible()
  await expect(page.getByText('Periksa waktu dalam pesan:', { exact: false })).toBeVisible()
})

test('evidence links survive reload, appear in exports, and source edits clear stale links', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Try an example', exact: true }).click()
  await page.getByRole('button', { name: 'Save & continue' }).click()
  await page.getByRole('button', { name: 'Use a manual draft' }).click()
  await page.getByRole('navigation').getByRole('button', { name: /Case materials/ }).click()
  const validPDF = await readFile(path.resolve('tests/fixtures/valid-reference.pdf'))
  await page.locator('input[type=file][accept="image/png,image/jpeg,application/pdf"]').setInputFiles({ name: 'linked-synthetic-reference.pdf', mimeType: 'application/pdf', buffer: validPDF })
  await expect(page.getByText('linked-synthetic-reference.pdf', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Link evidence', exact: true }).click()
  const editor = page.getByRole('region', { name: 'Link attachment' })
  await editor.getByRole('checkbox', { name: /^M3 / }).check()
  await editor.getByRole('checkbox', { name: /^Transfer 01 / }).check()
  await expect(page.getByRole('button', { name: 'Save & continue', exact: true })).toBeDisabled()
  await editor.getByRole('button', { name: 'Save evidence links', exact: true }).click()
  await expect(page.locator('.attachment-row')).toContainText('M3 · Transfer 01')
  await page.reload()
  await page.getByRole('navigation').getByRole('button', { name: /Case materials/ }).click()
  await expect(page.locator('.attachment-row')).toContainText('M3 · Transfer 01')
  await page.getByRole('button', { name: 'Link evidence', exact: true }).click()
  await expect(page.getByRole('region', { name: 'Link attachment' }).getByRole('checkbox', { name: /^M3 / })).toBeChecked()
  for (const width of [320, 390, 768, 1440]) {
    await page.setViewportSize({ width, height: 1000 })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `Link editor overflow at ${width}`).toBe(true)
  }
  await page.screenshot({ path: '../../docs/screenshots/13-evidence-links.png', fullPage: true })
  await page.getByRole('button', { name: 'Cancel', exact: true }).click()
  await page.getByRole('navigation').getByRole('button', { name: /Review & edit/ }).click()
  await expect(page.locator('.event-card').nth(2)).toContainText('Linked attachment: linked-synthetic-reference.pdf')
  for (const check of await page.getByRole('checkbox', { name: 'I have compared this entry with its source' }).all()) await check.check()
  await page.getByRole('checkbox', { name: /I have checked the accounts/ }).check()
  await page.getByRole('checkbox', { name: /I have checked the review flags/ }).check()
  await page.getByRole('button', { name: 'Confirm & continue', exact: true }).click()
  await mkdir(path.resolve('../../output/pdf'), { recursive: true })
  for (const language of ['en', 'id']) {
    await page.getByRole('combobox', { name: 'Language / Bahasa' }).selectOption(language)
    const downloaded = page.waitForEvent('download')
    await page.getByRole('button', { name: language === 'en' ? 'Download PDF report' : 'Unduh laporan PDF', exact: true }).click()
    const file = await downloaded
    await file.saveAs(path.resolve(`../../output/pdf/LaporSiap-synthetic-${language}.pdf`))
    expect((await readFile(await file.path() as string)).subarray(0, 5).toString()).toBe('%PDF-')
  }
  await page.getByRole('combobox', { name: 'Language / Bahasa' }).selectOption('en')
  const textDownload = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Download chronology TXT', exact: true }).click()
  const txt = await readFile(await (await textDownload).path() as string, 'utf8')
  expect(txt).toContain('User-selected links — messages: M3 | transfers:')
  await page.getByRole('navigation').getByRole('button', { name: /Case materials/ }).click()
  await page.getByRole('button', { name: 'Link evidence', exact: true }).click()
  await page.getByRole('button', { name: 'Save evidence links', exact: true }).click()
  await page.getByRole('navigation').getByRole('button', { name: /Export materials/ }).click()
  await expect(page.getByRole('button', { name: 'Download PDF report', exact: true })).toBeDisabled()
  await page.getByRole('navigation').getByRole('button', { name: /Case materials/ }).click()
  await page.getByRole('textbox', { name: 'Conversation', exact: true }).fill('Replacement source text, synthetic.')
  await page.getByLabel('Conversation format').selectOption('plain')
  await page.getByRole('button', { name: 'Save & continue', exact: true }).click()
  await page.getByRole('navigation').getByRole('button', { name: /Case materials/ }).click()
  await expect(page.locator('.attachment-row')).toContainText('No linked messages')
})
